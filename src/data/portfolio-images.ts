export function localPortfolioUrl(name: string | null | undefined): string | null {
  if (!name) return null
  const file = name.split('/').pop() ?? ''
  const stem = file.includes('.') ? file.slice(0, file.lastIndexOf('.')) : file
  if (!stem) return null
  return PORTFOLIO_IMAGE_FILES[stem] ?? null
}
